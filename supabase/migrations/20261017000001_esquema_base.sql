-- HIDRO360 - Migracion 1/3: esquema relacional hibrido.
--
-- Diseno: cada tabla guarda el documento completo en `datos jsonb` (la fuente de verdad del CONTENIDO sigue
-- siendo el modelo Pydantic de models/schemas.py) y, ademas, columnas tipadas para claves, estados, FKs, fechas y
-- busquedas frecuentes. El adaptador de data/database.py extrae las columnas del documento en cada escritura, de
-- modo que nunca se escriben a mano ni divergen.
--
-- Idempotente: se puede ejecutar varias veces (IF NOT EXISTS). Sin nombres de esquema: se crea en el primero del
-- search_path (en Supabase, `public`; en las pruebas, un esquema temporal).
--
-- ZONA HORARIA: los modelos usan datetime ingenuo (sin zona) en hora local de Panama (UTC-5, sin horario de
-- verano). Las columnas de fecha son `timestamptz` (UTC internamente): el adaptador interpreta el ingenuo en
-- HIDRO360_TZ (por defecto America/Panama) al derivar la columna. El documento `datos` conserva el texto original
-- SIN CAMBIOS, asi que la lectura devuelve exactamente lo escrito (ida y vuelta sin perdida).
--
-- IDs: se conservan los enteros autoincrementales del modelo (IDENTITY ... BY DEFAULT, permite fijar ids al migrar
-- desde SQLite) y las claves de texto (sectores.nombre, cisternas.id, usuarios.id, fotos.id, dispositivos.id).
--
-- FKs (criterio): ver docs/BASE_DE_DATOS.md. Resumen:
--   misiones.cisterna_id    -> cisternas   ON DELETE CASCADE   (una mision no existe sin su vehiculo; recargar la demo la borra de todos modos)
--   eventos_mision.mision_id-> misiones    ON DELETE CASCADE   (NULL si el evento fue rechazado por apuntar a una mision inexistente)
--   recomendaciones.reporte_id -> reportes ON DELETE CASCADE   (la recomendacion es derivada del reporte)
--   dispositivos.cisterna_id-> cisternas   DEFERRABLE INITIALLY DEFERRED, sin accion: las terminales SOBREVIVEN a
--     "Cargar datos de ejemplo" (que borra y recrea cisternas dentro de una transaccion); solo falla el COMMIT si
--     al final alguna terminal apunta a una cisterna que ya no existe.
--   fotos / decisiones_duplicado / usuarios / sesiones: SIN FK hacia reportes: deben sobrevivir al reinicio de la demo.

-- ---------------------------------------------------------------------------------------------------- control
CREATE TABLE IF NOT EXISTS schema_migraciones (
    version   text PRIMARY KEY,
    aplicada  timestamptz NOT NULL DEFAULT now(),
    checksum  text
);

-- ---------------------------------------------------------------------------------------------------- catalogos
CREATE TABLE IF NOT EXISTS sectores (
    nombre              text PRIMARY KEY,
    poblacion_estimada  integer CHECK (poblacion_estimada IS NULL OR poblacion_estimada >= 0),
    vulnerabilidad      text CHECK (vulnerabilidad IS NULL OR vulnerabilidad IN ('baja', 'media', 'alta', 'crítica')),
    lat                 double precision CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
    lng                 double precision CHECK (lng IS NULL OR lng BETWEEN -180 AND 180),
    ficticio            boolean NOT NULL DEFAULT true,
    datos               jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS cisternas (
    id                  text PRIMARY KEY,
    capacidad_litros    integer CHECK (capacidad_litros IS NULL OR capacidad_litros >= 0),
    litros_disponibles  integer CHECK (litros_disponibles IS NULL OR litros_disponibles >= 0),
    estado              text CHECK (estado IS NULL OR estado IN ('disponible', 'en_mantenimiento', 'fuera_de_servicio')),
    sector_base         text,
    ficticio            boolean NOT NULL DEFAULT true,
    datos               jsonb NOT NULL
);

-- ---------------------------------------------------------------------------------------------------- reportes
CREATE TABLE IF NOT EXISTS reportes (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado              text CHECK (estado IS NULL OR estado IN ('por_revisar', 'confirmado', 'duplicado', 'en_plan', 'rechazado')),
    sector              text,
    severidad           text CHECK (severidad IS NULL OR severidad IN ('baja', 'media', 'alta', 'crítica')),
    fecha_creacion      timestamptz,
    codigo_seguimiento  text UNIQUE,                 -- HID-XXXXXXXX; los reportes antiguos no lo tienen (NULL no choca)
    clave_idempotencia  text,
    canal               text,
    duplicado_de        bigint,
    lat                 double precision CHECK (lat IS NULL OR lat BETWEEN -90 AND 90),
    lng                 double precision CHECK (lng IS NULL OR lng BETWEEN -180 AND 180),
    ficticio            boolean NOT NULL DEFAULT false,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_reportes_estado          ON reportes (estado);
CREATE INDEX IF NOT EXISTS ix_reportes_sector          ON reportes (sector);
CREATE INDEX IF NOT EXISTS ix_reportes_fecha           ON reportes (fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS ix_reportes_clave_idemp     ON reportes (clave_idempotencia) WHERE clave_idempotencia IS NOT NULL;

CREATE TABLE IF NOT EXISTS planes (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado              text CHECK (estado IS NULL OR estado IN ('propuesto', 'aprobado', 'rechazado')),
    version             integer,
    fecha_creacion      timestamptz,
    metodo              text,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_planes_estado ON planes (estado);

CREATE TABLE IF NOT EXISTS decisiones_duplicado (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id          bigint,
    otro_id             bigint,
    es_duplicado        boolean,
    responsable         text,
    fecha               timestamptz,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_decisiones_dup_reporte ON decisiones_duplicado (reporte_id);

-- ---------------------------------------------------------------------------------------------------- auditoria
-- Append-only (ver migracion 2). `datos_texto` guarda el JSON EXACTO que se hasheo: jsonb normaliza (orden de
-- claves, formato numerico) y la cadena de hashes debe poder verificarse sin depender de esa normalizacion.
-- UNIQUE(hash_previo) impide bifurcar la cadena aunque dos escritores se solaparan.
CREATE TABLE IF NOT EXISTS auditoria (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha               timestamptz,
    responsable         text,
    accion              text,
    entidad             text,
    entidad_id          text,
    hash_previo         text NOT NULL,
    hash                text NOT NULL UNIQUE,
    datos               jsonb NOT NULL,
    datos_texto         text NOT NULL,
    CONSTRAINT auditoria_hash_previo_unico UNIQUE (hash_previo)
);
CREATE INDEX IF NOT EXISTS ix_auditoria_entidad ON auditoria (entidad, entidad_id);
CREATE INDEX IF NOT EXISTS ix_auditoria_fecha   ON auditoria (fecha);

-- ---------------------------------------------------------------------------------------------------- cuentas y sesiones
CREATE TABLE IF NOT EXISTS usuarios (
    id                  text PRIMARY KEY,
    usuario             text,
    rol                 text CHECK (rol IS NULL OR rol IN ('administrador', 'usuario')),
    activo              boolean,
    creado              timestamptz,
    datos               jsonb NOT NULL
);

-- id = SHA-256 (hex) del token de sesion: el token en claro nunca se guarda.
CREATE TABLE IF NOT EXISTS sesiones (
    id                  text PRIMARY KEY,
    usuario             text,
    expira              timestamptz,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_sesiones_expira  ON sesiones (expira);
CREATE INDEX IF NOT EXISTS ix_sesiones_usuario ON sesiones (usuario);

-- Limites de tasa compartidos entre instancias (serverless). `instante` lo pone el servidor.
CREATE TABLE IF NOT EXISTS limites (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave               text NOT NULL,
    instante            timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX IF NOT EXISTS ix_limites_clave_instante ON limites (clave, instante);

-- ---------------------------------------------------------------------------------------------------- fotos y flota
-- Solo metadatos; el archivo vive en MEDIA_DIR o en el bucket privado de Storage.
CREATE TABLE IF NOT EXISTS fotos (
    id                  text PRIMARY KEY,
    reporte_id          bigint,
    tipo_mime           text CHECK (tipo_mime IS NULL OR tipo_mime IN ('image/jpeg', 'image/png', 'image/webp')),
    bytes               integer CHECK (bytes IS NULL OR bytes >= 0),
    sha256              text,
    fecha               timestamptz,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_fotos_reporte ON fotos (reporte_id);

CREATE TABLE IF NOT EXISTS dispositivos (
    id                  text PRIMARY KEY,                    -- = cisterna_id
    cisterna_id         text NOT NULL,
    token_hash          text,
    activo              boolean,
    ultima_conexion     timestamptz,
    datos               jsonb NOT NULL,
    CONSTRAINT dispositivos_cisterna_fk FOREIGN KEY (cisterna_id) REFERENCES cisternas (id)
        DEFERRABLE INITIALLY DEFERRED
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dispositivos_token_hash ON dispositivos (token_hash)
    WHERE token_hash IS NOT NULL AND token_hash <> '';

CREATE TABLE IF NOT EXISTS misiones (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cisterna_id         text NOT NULL REFERENCES cisternas (id) ON DELETE CASCADE,
    estado              text CHECK (estado IS NULL OR estado IN ('asignada', 'en_curso', 'completada', 'cancelada')),
    plan_id             bigint,
    recomendacion_id    bigint,
    creada              timestamptz,
    ficticio            boolean NOT NULL DEFAULT false,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_misiones_cisterna ON misiones (cisterna_id, estado);
CREATE INDEX IF NOT EXISTS ix_misiones_estado   ON misiones (estado);

-- mision_id es NULL cuando el evento se rechazo por apuntar a una mision que no existe (el numero declarado queda en `datos`).
CREATE TABLE IF NOT EXISTS eventos_mision (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mision_id           bigint REFERENCES misiones (id) ON DELETE CASCADE,
    uid                 text NOT NULL,
    cisterna_id         text,
    tipo                text CHECK (tipo IS NULL OR tipo IN ('llegada', 'entrega', 'incidencia')),
    resultado           text CHECK (resultado IS NULL OR resultado IN ('aplicado', 'duplicado', 'rechazado')),
    parada_orden        integer,
    fecha_servidor      timestamptz,
    datos               jsonb NOT NULL
);
-- Idempotencia: un uid solo puede estar APLICADO una vez (los rechazados/duplicados se registran con el mismo uid).
CREATE UNIQUE INDEX IF NOT EXISTS ux_eventos_uid_aplicado ON eventos_mision (uid) WHERE resultado = 'aplicado';
CREATE INDEX IF NOT EXISTS ix_eventos_mision ON eventos_mision (mision_id, id);

CREATE TABLE IF NOT EXISTS recomendaciones (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id          bigint NOT NULL REFERENCES reportes (id) ON DELETE CASCADE,
    estado              text CHECK (estado IS NULL OR estado IN ('propuesta', 'aprobada', 'modificada', 'rechazada')),
    proveedor           text,
    fecha               timestamptz,
    mision_id           bigint,
    datos               jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_recomendaciones_reporte ON recomendaciones (reporte_id);
CREATE INDEX IF NOT EXISTS ix_recomendaciones_estado  ON recomendaciones (estado);
